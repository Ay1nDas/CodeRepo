int power(int a, int b, int m) {
    int ans = 1, temp = a;
    while(b > 0) {
        if(b%2 == 1) ans = (ans * temp) % m;
        b /= 2;

        temp = (temp * temp) % m ;
    }
    return ans ;
}
int modinv(int a, int m) {
    return power(a, m-2, m);
}

// Sieve of Eratosthenes
const int MAXN = 1e6 + 5;
vector<bool> is_prime(MAXN, true);
void sieve() {
    is_prime[0] = is_prime[1] = false;
    for (int i = 2; i * i < MAXN; ++i) {
        if (is_prime[i]) {
            for (int j = i * i; j < MAXN; j += i)
                is_prime[j] = false;
        }
    }
}


int extended_gcd(int a, int b, int &x, int &y) {
    if (b == 0) {
        x = 1;
        y = 0;
        return a;
    }
    int x1, y1;
    int d = extended_gcd(b, a % b, x1, y1);
    x = y1;
    y = x1 - y1 * (a / b);
    return d;
}

struct DSU {
    vi parent, size;
    DSU(int n) {
        parent.resize(n); size.resize(n, 1);
        iota(all(parent), 0);
    }
    int find(int x) {
        if (x == parent[x]) return x;
        return parent[x] = find(parent[x]);
    }
    void unite(int x, int y) {
        x = find(x); y = find(y);
        if (x == y) return;
        if (size[x] < size[y]) swap(x, y);
        parent[y] = x;
        size[x] += size[y];
    }
};

int binary_search_example(vi &a, int target) {
    int l = 0, r = a.size() - 1, ans = -1;
    while (l <= r) {
        int m = (l + r) / 2;
        if (a[m] <= target) {
            ans = m;
            l = m + 1;
        } else r = m - 1;
    }
    return ans;
}


struct SegmentTree {
    int n;
    vi tree;
    SegmentTree(int sz) { n = sz; tree.assign(4*n, 0); }
    void build(vi &a, int v, int tl, int tr) {
        if (tl == tr) tree[v] = a[tl];
        else {
            int tm = (tl + tr) / 2;
            build(a, v*2, tl, tm);
            build(a, v*2+1, tm+1, tr);
            tree[v] = tree[v*2] + tree[v*2+1];
        }
    }
    int query(int v, int tl, int tr, int l, int r) {
        if (l > r) return 0;
        if (l == tl && r == tr) return tree[v];
        int tm = (tl + tr) / 2;
        return query(v*2, tl, tm, l, min(r, tm)) +
               query(v*2+1, tm+1, tr, max(l, tm+1), r);
    }
    void update(int v, int tl, int tr, int pos, int new_val) {
        if (tl == tr) tree[v] = new_val;
        else {
            int tm = (tl + tr) / 2;
            if (pos <= tm) update(v*2, tl, tm, pos, new_val);
            else update(v*2+1, tm+1, tr, pos, new_val);
            tree[v] = tree[v*2] + tree[v*2+1];
        }
    }
};

struct FenwickTree {
    vi bit; int n;
    FenwickTree(int n) { this->n = n; bit.assign(n+1, 0); }
    void add(int i, int val) {
        for (++i; i <= n; i += i & -i) bit[i] += val;
    }
    int sum(int i) {
        int res = 0;
        for (++i; i > 0; i -= i & -i) res += bit[i];
        return res;
    }
    int range_sum(int l, int r) {
        return sum(r) - sum(l-1);
    }
};

struct SparseTable {
    vvi st;
    vi log;
    SparseTable(vi &a) {
        int n = a.size();
        log.resize(n+1);
        log[1] = 0;
        for (int i = 2; i <= n; ++i) log[i] = log[i/2] + 1;
        st.assign(log[n]+1, vi(n));
        for (int i = 0; i < n; ++i) st[0][i] = a[i];
        for (int j = 1; j <= log[n]; ++j)
            for (int i = 0; i + (1 << j) <= n; ++i)
                st[j][i] = min(st[j-1][i], st[j-1][i+(1<<(j-1))]);
    }
    int query(int l, int r) {
        int j = log[r-l+1];
        return min(st[j][l], st[j][r-(1<<j)+1]);
    }
};

vi z_function(string s) {
    int n = s.size();
    vi z(n);
    int l = 0, r = 0;
    for (int i = 1; i < n; i++) {
        if (i <= r) z[i] = min(r - i + 1, z[i - l]);
        while (i + z[i] < n && s[z[i]] == s[i + z[i]]) z[i]++;
        if (i + z[i] - 1 > r) l = i, r = i + z[i] - 1;
    }
    return z;
}

vi prefix_function(string s) {
    int n = s.length();
    vi pi(n);
    for (int i = 1; i < n; i++) {
        int j = pi[i-1];
        while (j > 0 && s[i] != s[j]) j = pi[j-1];
        if (s[i] == s[j]) j++;
        pi[i] = j;
    }
    return pi;
}


